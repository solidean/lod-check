"""Compiles shaders/probe.comp to the SPIR-V words in shaders/probe.comp.spv.inc.

The SPIR-V is committed so building lod-check needs no shader compiler.
Needs glslangValidator, from the Vulkan SDK or a distribution's glslang package.
"""

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = root / "shaders" / "probe.comp"
target = root / "shaders" / "probe.comp.spv.inc"


def find_glslang() -> str:
    found = shutil.which("glslangValidator")
    if found:
        return found
    sdk = os.environ.get("VULKAN_SDK")
    if sdk:
        for sub in ("Bin", "bin"):
            for name in ("glslangValidator.exe", "glslangValidator"):
                candidate = Path(sdk) / sub / name
                if candidate.exists():
                    return str(candidate)
    sys.exit("glslangValidator not found: install the Vulkan SDK or glslang")


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        spv = Path(tmp) / "probe.spv"
        subprocess.run([find_glslang(), "-V", "--target-env", "vulkan1.1", "-o", str(spv), str(source)], check=True)
        data = spv.read_bytes()
    words = [int.from_bytes(data[i : i + 4], "little") for i in range(0, len(data), 4)]
    lines = ["// Generated by tools/compile-spirv.py from probe.comp; do not edit."]
    for i in range(0, len(words), 8):
        lines.append(", ".join(f"0x{w:08x}" for w in words[i : i + 8]) + ",")
    target.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"wrote {target.relative_to(root)} ({len(words)} words)")


if __name__ == "__main__":
    main()
